    public void tampilkanData(List<Buku> daftarBuku) {
        DefaultTableModel model = (DefaultTableModel) tblBuku.getModel();
        model.setRowCount(0);
        for (Buku buku : daftarBuku) {
            model.addRow(new Object[] {
                    buku.getJudul(),
                    buku.getPenulis(),
                    buku.getTahunTerbit()
            });
        }
    }

    public void tampilkanPeringatan(String judul, String pesan) {
        JOptionPane.showMessageDialog(this, pesan, judul, JOptionPane.WARNING_MESSAGE);
    }

    public void tampilkanInfo(String judul, String pesan) {
        JOptionPane.showMessageDialog(this, pesan, judul, JOptionPane.INFORMATION_MESSAGE);
    }
    
